@app.route('/api/inpaint', methods=['POST'])
def api_inpaint():
    """AI inpainting endpoint with improved box handling"""
    if not AI_AVAILABLE:
        return jsonify({
            'error': 'AI not available',
            'message': 'Chức năng AI chưa được cài đặt. Vui lòng cài đặt torch và opencv.',
            'install_guide': 'pip install torch opencv-python'
        }), 501
    
    try:
        # Get uploaded files
        if 'file' not in request.files:
            return jsonify({'error': 'No image file uploaded'}), 400
        
        file = request.files['file']
        if file.filename == '':
            return jsonify({'error': 'No file selected'}), 400
        
        # Read image
        import cv2
        import numpy as np
        from PIL import Image
        
        # Convert uploaded file to PIL Image
        image = Image.open(file.stream).convert('RGB')
        image_array = np.array(image)
        
        # Get boxes data for mask creation - handle both formats
        boxes_data = request.form.get('boxes', '[]')
        try:
            boxes = json.loads(boxes_data)
        except:
            boxes = []
        
        print(f"[DEBUG] Received boxes data: {boxes}")
        
        # Create mask from boxes
        mask = np.zeros(image_array.shape[:2], dtype=np.uint8)
        
        if not boxes:
            # Create a small test mask in the center for demo
            h, w = image_array.shape[:2]
            mask[h//4:3*h//4, w//4:3*w//4] = 255
            print(f"[DEBUG] No boxes provided, created test mask")
        else:
            # Handle different box formats
            for i, box in enumerate(boxes):
                try:
                    # Frontend sends boxes as objects with x, y, width, height
                    if isinstance(box, dict):
                        x = int(float(box.get('x', 0)))
                        y = int(float(box.get('y', 0)))
                        w = int(float(box.get('width', 50)))
                        h = int(float(box.get('height', 50)))
                    # Handle array format [x1, y1, x2, y2]
                    elif isinstance(box, (list, tuple)) and len(box) >= 4:
                        x1, y1, x2, y2 = box[:4]
                        x = int(float(x1))
                        y = int(float(y1))
                        w = int(float(x2)) - x
                        h = int(float(y2)) - y
                    else:
                        print(f"[WARNING] Invalid box format: {box}")
                        continue
                    
                    # Ensure coordinates are within image bounds
                    img_h, img_w = image_array.shape[:2]
                    x = max(0, min(x, img_w - 1))
                    y = max(0, min(y, img_h - 1))
                    w = max(1, min(w, img_w - x))
                    h = max(1, min(h, img_h - y))
                    
                    # Add to mask
                    mask[y:y+h, x:x+w] = 255
                    print(f"[DEBUG] Added box {i}: x={x}, y={y}, w={w}, h={h}")
                    
                except (ValueError, KeyError, TypeError) as e:
                    print(f"[WARNING] Invalid box data: {box}, error: {e}")
                    continue
        
        # Check if mask has any content
        if np.sum(mask) == 0:
            return jsonify({
                'error': 'No valid mask created',
                'message': 'Không thể tạo mask từ dữ liệu boxes'
            }), 400
        
        print(f"[DEBUG] Created mask with {np.sum(mask > 0)} pixels")
        
        # Simple inpainting using OpenCV
        result = cv2.inpaint(image_array, mask, 3, cv2.INPAINT_TELEA)
        
        # Convert back to PIL Image
        result_image = Image.fromarray(result)
        
        # Convert to bytes
        img_io = io.BytesIO()
        result_image.save(img_io, 'JPEG', quality=95)
        img_io.seek(0)
        
        return Response(
            img_io.getvalue(),
            mimetype='image/jpeg',
            headers={
                'Content-Disposition': 'attachment; filename=inpainted.jpg'
            }
        )
        
    except Exception as e:
        print(f"[ERROR] AI inpainting failed: {str(e)}")
        import traceback
        traceback.print_exc()
        return jsonify({
            'error': 'AI inpainting failed',
            'message': 'Không thể thực hiện AI inpainting',
            'details': str(e)
        }), 500

