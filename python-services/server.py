    """Finalize chunked upload and save complete file"""
    try:
        data = request.get_json()
        upload_id = data.get('upload_id')
        total_chunks = data.get('total_chunks')
        original_filename = data.get('original_filename')
        
        if upload_id not in chunked_uploads:
            return jsonify({'error': 'Invalid upload_id'}), 400
        
        upload_info = chunked_uploads[upload_id]
        
        # Check all chunks are present
        if len(upload_info['chunks']) != total_chunks:
            return jsonify({'error': 'Missing chunks'}), 400
        
        # Combine chunks
        os.makedirs(UPLOADS_DIR, exist_ok=True)
        file_path = os.path.join(UPLOADS_DIR, f"{uuid.uuid4()}_{original_filename}")
        
        with open(file_path, 'wb') as f:
            for i in range(total_chunks):
                if i in upload_info['chunks']:
                    f.write(upload_info['chunks'][i])
        
        # Clean up
        del chunked_uploads[upload_id]
        
        return jsonify({
            'success': True,
            'file_path': file_path,
            'filename': original_filename
        })
        
    except Exception as e:
        print(f"[ERROR] Finalize upload failed: {str(e)}")
        return jsonify({'error': str(e)}), 500

