def _make_thumbnail(file_path, ext, max_size=400):
    """Generate thumbnail + dimensions in mm from source file"""
    from PIL import Image, ImageOps
    from io import BytesIO
    import fitz
    
    if ext == '.pdf':
        doc = fitz.open(file_path)
        page = doc[0]
        pix = page.get_pixmap(dpi=150, alpha=False)
        img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)
        # PDF dimensions from mediabox (points -> mm)
        rect = page.rect
        w_mm = round(rect.width * 0.352778, 1)
        h_mm = round(rect.height * 0.352778, 1)
        doc.close()
    else:
        img = Image.open(file_path)
        img = ImageOps.exif_transpose(img)
        if img.mode == 'RGBA':
            bg = Image.new('RGB', img.size, (255, 255, 255))
            bg.paste(img, mask=img.split()[3])
            img = bg
        elif img.mode not in ('RGB',):
            img = img.convert('RGB')
        # Assume 300 DPI for images
        w_mm = round(img.width / 300 * 25.4, 1)
        h_mm = round(img.height / 300 * 25.4, 1)
    
    # Resize for thumbnail
    img.thumbnail((max_size, max_size), Image.Resampling.LANCZOS)
    
    buf = BytesIO()
    img.save(buf, format='JPEG', quality=90)
    buf.seek(0)
    thumb_b64 = f"data:image/jpeg;base64,{base64.b64encode(buf.read()).decode()}"
    
    return thumb_b64, w_mm, h_mm


