@app.route('/api/render-sheet-preview', methods=['POST'])
def render_sheet_preview():
    """Render a single sheet preview as PNG image - same logic as PDF but outputs image"""
    try:
        from PIL import Image, ImageDraw
        
        form = request.form
        plan_items = json.loads(form.get('planData', '[]'))
        file_ids = json.loads(form.get('fileIds', '[]'))
        pages_meta = json.loads(form.get('pagesData', '[]'))
        
        page_w = float(form.get('pageW', 330))
        page_h = float(form.get('pageH', 480))
        item_w = float(form.get('itemW', 100))
        item_h = float(form.get('itemH', 120))
        fit_mode = form.get('fitMode', 'stretch')
        shape = form.get('shape', 'rect')
        auto_rotate = _is_truthy(form.get('autoRotate', '0'))
        sheet_index = int(form.get('sheetIndex', 0))
        data_mode = int(form.get('dataMode', 1))
        standard_qty = int(form.get('standardQty', 1))
        x_up_qty = int(form.get('xUpQty', 1))
        preview_dpi = int(form.get('previewDpi', 72))
        bg_color = form.get('backgroundColor', '#ffffff')
        
        # Convert mm to pixels
        scale = preview_dpi / 25.4
        pw = int(page_w * scale)
        ph = int(page_h * scale)
        
        # Parse bg color
        try:
            r, g, b = int(bg_color[1:3], 16), int(bg_color[3:5], 16), int(bg_color[5:7], 16)
        except:
            r, g, b = 255, 255, 255
        
        canvas = Image.new('RGB', (pw, ph), (r, g, b))
        
        # Load source images from file IDs
        source_images = []
        for fid in file_ids:
            if fid in source_files:
                path = source_files[fid]['path']
                ext = os.path.splitext(path)[1].lower()
                try:
                    if ext == '.pdf':
                        import fitz
                        doc = fitz.open(path)
                        page = doc[0]
                        pix = page.get_pixmap(dpi=preview_dpi, alpha=False)
                        img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)
                        doc.close()
                    else:
                        img = Image.open(path).convert('RGB')
                    source_images.append(img)
                except Exception as e:
                    print(f"[PREVIEW] Failed to load {fid}: {e}")
                    source_images.append(None)
            else:
                source_images.append(None)
        
        # Get page for slot (same logic as PDF generation)
        def get_page_idx(slot_idx):
            n = len(source_images)
            if n == 0: return -1
            items_per_sheet = len(plan_items)
            if data_mode == 1:
                gi = sheet_index * items_per_sheet + slot_idx
                return (gi // standard_qty) % n
            elif data_mode == 4:
                return (sheet_index // x_up_qty) % n
            else:
                gi = sheet_index * items_per_sheet + slot_idx
                return gi % n
        
        is_flip_shape = shape in ('triangle', 'trapezoid', 'hexagon')
        effective_item_h = item_w if shape == 'circle' else item_h
        
        for slot_idx, item in enumerate(plan_items):
            page_idx = get_page_idx(slot_idx)
            if page_idx < 0 or page_idx >= len(source_images) or source_images[page_idx] is None:
                continue
            
            src = source_images[page_idx]
            
            # Calculate slot dimensions
            eff_item_h = item_w if shape == 'circle' else item_h
            if is_flip_shape:
                sw, sh = item_w, eff_item_h
            elif item.get('rot', False):
                sw, sh = eff_item_h, item_w
            else:
                sw, sh = item_w, eff_item_h
            if 'w' in item and item['w'] is not None:
                sw = float(item['w'])
            if 'h' in item and item['h'] is not None:
                sh = float(item['h'])
            if shape == 'circle':
                sh = sw
            
            tw = int(sw * scale)
            th = int(sh * scale)
            if tw <= 0 or th <= 0: continue
            
            img = src.copy()
            from PIL import ImageOps
            
            if item.get('totalRotation') is not None:
                tot_rot = float(item['totalRotation']) % 360
                is_odd_90 = (tot_rot % 180) != 0
                elem_tw = th if is_odd_90 else tw
                elem_th = tw if is_odd_90 else th
                
                if fit_mode == 'stretch':
                    img = img.resize((elem_tw, elem_th), Image.Resampling.LANCZOS)
                elif fit_mode == 'fill':
                    img = ImageOps.fit(img, (elem_tw, elem_th), method=Image.Resampling.LANCZOS)
                elif fit_mode == 'fit':
                    img = ImageOps.contain(img, (elem_tw, elem_th), method=Image.Resampling.LANCZOS)
                    bg = Image.new('RGB', (elem_tw, elem_th), (r, g, b))
                    bg.paste(img, ((elem_tw - img.width) // 2, (elem_th - img.height) // 2))
                    img = bg
                else:
                    img = img.resize((elem_tw, elem_th), Image.Resampling.LANCZOS)
                
                if tot_rot != 0:
                    img = img.rotate(-tot_rot, expand=True)
                if img.size != (tw, th):
                    img = ImageOps.fit(img, (tw, th), method=Image.Resampling.LANCZOS)
            else:
                # Legacy fallback
                if auto_rotate:
                    src_ratio = img.width / img.height
                    dst_ratio = tw / th
                    if (src_ratio > 1 and dst_ratio < 1) or (src_ratio < 1 and dst_ratio > 1):
                        img = img.rotate(-90, expand=True)
                
                if fit_mode == 'stretch':
                    img = img.resize((tw, th), Image.Resampling.LANCZOS)
                elif fit_mode == 'fill':
                    img = ImageOps.fit(img, (tw, th), method=Image.Resampling.LANCZOS)
                elif fit_mode == 'fit':
                    img = ImageOps.contain(img, (tw, th), method=Image.Resampling.LANCZOS)
                    bg = Image.new('RGB', (tw, th), (r, g, b))
                    bg.paste(img, ((tw - img.width) // 2, (th - img.height) // 2))
                    img = bg
                else:
                    img = img.resize((tw, th), Image.Resampling.LANCZOS)
                
                if is_flip_shape and item.get('rot', False):
                    img = img.rotate(180, expand=False)
                elif item.get('rot', False) and not is_flip_shape:
                    img = img.rotate(90, expand=True)
                    if img.size != (tw, th):
                        img = ImageOps.fit(img, (tw, th), method=Image.Resampling.LANCZOS)
            
            # Paste onto canvas
            x = int(item['x'] * scale)
            y = int(item['y'] * scale)
            try:
                canvas.paste(img, (x, y))
            except:
                pass
        
        # Draw grid lines (light gray)
        draw = ImageDraw.Draw(canvas)
        for item in plan_items:
            if is_flip_shape:
                sw, sh = item_w, effective_item_h
            elif item.get('rot', False):
                sw, sh = effective_item_h, item_w
            else:
                sw, sh = item_w, effective_item_h
            x1 = int(item['x'] * scale)
            y1 = int(item['y'] * scale)
            x2 = x1 + int(sw * scale)
            y2 = y1 + int(sh * scale)
            draw.rectangle([x1, y1, x2, y2], outline=(200, 200, 200), width=1)
        
        # Output as JPEG for speed
        buf = BytesIO()
        canvas.save(buf, format='JPEG', quality=85)
        buf.seek(0)
        
        return Response(buf.getvalue(), mimetype='image/jpeg',
                       headers={'Cache-Control': 'public, max-age=5'})
    
    except Exception as e:
        print(f"[PREVIEW] Error: {e}")
        import traceback; traceback.print_exc()
        return jsonify({'error': str(e)}), 500

