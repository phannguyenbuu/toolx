// Safe lock avoiding browser Web Locks 'steal' race condition between tabs / clients
const safeLock = async (name: string, acquireTimeout: number, fn: () => Promise<any>) => {
  try {
    return await fn();
  } catch (err: any) {
    if (err?.name !== 'AbortError') {
      console.warn('[Supabase Auth Lock]', err);
    }
  }
};

